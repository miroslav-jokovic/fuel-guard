-- 0526 — print stations, printers, default printers and the print queue (PRINTERS-AND-SCANNERS-PLAN.md
-- step PS1; D-PS1, D-PS3, D-PS4).
--
-- ── THE GAP ─────────────────────────────────────────────────────────────────────────────────────
-- The owner ruled on 2026-10-28 that a printer is chosen ONCE in Settings and printing never asks
-- which one again, from any device. A web page cannot choose a printer or skip the print dialog —
-- that is a browser security boundary on every operating system — and the shop's MUNBYN RW403B has
-- no network of its own (USB and Bluetooth only). So the server prints: a person presses Print on
-- any device, the API queues a job for the default printer, and a PRINT STATION (our program, on the
-- office Windows PC per Q-PS1) that is plugged into the printer claims the job over an outbound
-- connection and writes its bytes to the printer.
--
-- ── WHY FOUR TABLES ─────────────────────────────────────────────────────────────────────────────
-- `print_stations` — the always-on machine. It authenticates with a long-lived token the API only
--   ever stores as a SHA-256 hash, issued in exchange for a short pairing code shown once in
--   Settings (also stored hashed, with an expiry). It reports what printers its operating system
--   sees (`discovered_printers`), which is how Settings offers a list rather than a typed name.
-- `printers` — one row per physical printer the office named: which station drives it, the name
--   its operating system knows it by, its LANGUAGE (D-PS3: the RW403B speaks a TSPL subset; a
--   Zebra later is a row with `zpl`, not a release), its label stock and its X/Y nudge. The nudge
--   lives on the printer for the reason 0283 gave for `maintenance_print_profiles`: registration is
--   a property of the machine, not of a person or a browser.
-- `print_defaults` — D-PS4: one default per purpose for the organization, and optionally one per
--   person, which wins. A row, not a column on `printers`, so "exactly one default" is a unique
--   index instead of a convention two writers can break.
-- `print_jobs` — the queue AND the record. Every press of Print is a row the person can watch go
--   queued → sent → printed, or see fail with a reason. The id is generated by the client, so a
--   retried tap on a flaky connection inserts the same id twice and the second insert is a no-op
--   (D-INV27's rule, applied to printing).
--
-- ── WHY "UNKNOWN" IS A STATUS ───────────────────────────────────────────────────────────────────
-- A station that took a job and then went silent (a crash, a pulled cable, the PC restarting) may or
-- may not have printed it. Putting the job back in the queue would print a second label whenever the
-- first one did come out; failing it would hide one that did. `unknown` says exactly what is known,
-- and the screen offers Retry. A late report from the station still settles it (unknown → printed /
-- failed), because that is the truth arriving late, not a second outcome.
--
-- ── WHY THE PAYLOAD IS STORED ───────────────────────────────────────────────────────────────────
-- The API renders the label into the printer's language when the job is queued (D-PS2), so a job
-- prints exactly what was asked even if the printer's stock or nudge is changed while it waits, and
-- the station stays a dumb pipe that needs no renderer and no driver. A 2" label is ~20 KB; the cap
-- below allows a few hundred. Pruning old payloads is a retention step owed to PS2, not done here.
--
-- ── WHAT WAS REJECTED ───────────────────────────────────────────────────────────────────────────
-- * A composite (id, org_id) foreign key for "same organization": it gives PostgREST two
--   relationships between the same tables and breaks embeds (PGRST201, the 0505/#1680 incident).
--   A guard trigger says it once instead.
-- * Re-queueing a stale `sent` job: prints twice whenever the first attempt worked (above).
-- * Client RLS policies: every read and write goes through the API (service role), which org-filters
--   itself. Zero policies = deny-all to browsers, on purpose.
--
-- Error codes: PS001 another org's row named; PS002 an illegal job status change; PS003 a job's
-- content or printer changed after it was queued; PS004 a retired printer named as a default or for
-- a new job; PS005 a station that does not drive the job's printer.
--
-- Rollback: drop function public.print_claim_next_job(uuid), public.print_finish_job(uuid, uuid, boolean, text);
--           drop table public.print_jobs, public.print_defaults, public.printers, public.print_stations;
--           drop function public.print_rows_same_org(), public.print_jobs_guard();

create table if not exists public.print_stations (
  id                  uuid        primary key default gen_random_uuid(),
  org_id              uuid        not null references public.organizations(id) on delete cascade,
  -- What the office calls the machine ("Office PC"), which is how somebody recognises it in Settings.
  name                text        not null check (length(btrim(name)) between 1 and 80),
  -- A pairing code is shown once; only its hash is kept, and only until it is used or expires.
  pairing_code_hash   text        check (pairing_code_hash ~ '^[0-9a-f]{64}$'),
  pairing_expires_at  timestamptz,
  -- The station's credential, as a SHA-256 hex digest. Null until paired.
  token_hash          text        unique check (token_hash ~ '^[0-9a-f]{64}$'),
  paired_at           timestamptz,
  last_seen_at        timestamptz,
  agent_version       text        check (length(agent_version) <= 40),
  host_name           text        check (length(host_name) <= 120),
  -- What the station's operating system reports as installed printers: [{ "name": … }, …].
  discovered_printers jsonb       not null default '[]'::jsonb check (jsonb_typeof(discovered_printers) = 'array'),
  revoked_at          timestamptz,
  created_at          timestamptz not null default now(),
  created_by          uuid        references auth.users(id) on delete set null,
  updated_at          timestamptz not null default now(),
  constraint print_stations_name_unique unique (org_id, name),
  constraint print_stations_pairing_pair check ((pairing_code_hash is null) = (pairing_expires_at is null)),
  constraint print_stations_paired_pair check ((token_hash is null) = (paired_at is null))
);

comment on table public.print_stations is
  'An always-on machine running the Silvicom print station program, plugged into one or more printers (PRINTERS-AND-SCANNERS-PLAN.md, 0526).';

create table if not exists public.printers (
  id            uuid        primary key default gen_random_uuid(),
  org_id        uuid        not null references public.organizations(id) on delete cascade,
  station_id    uuid        not null references public.print_stations(id) on delete restrict,
  name          text        not null check (length(btrim(name)) between 1 and 80),
  -- The name the station's operating system knows the printer by; the station prints to it.
  system_name   text        not null check (length(btrim(system_name)) between 1 and 200),
  -- D-PS3: the language decides the renderer. Only TSPL has one today (the RW403B).
  language      text        not null default 'tspl' check (language in ('tspl')),
  -- A label stock id from @silvicom/qr's LABEL_PRESETS. Validated by the API against that catalogue
  -- rather than restated here, so a new stock is not a migration.
  stock_id      text        not null check (length(stock_id) between 1 and 40),
  dpi           integer     not null default 203 check (dpi in (203, 300)),
  -- The nudge, in printer dots; positive is right and down (0283's convention). Half an inch at 203
  -- dpi bounds it: a real offset is millimetres, and the bound turns a typo into a refusal.
  offset_x_dots integer     not null default 0 check (offset_x_dots between -100 and 100),
  offset_y_dots integer     not null default 0 check (offset_y_dots between -100 and 100),
  retired_at    timestamptz,
  created_at    timestamptz not null default now(),
  created_by    uuid        references auth.users(id) on delete set null,
  updated_at    timestamptz not null default now(),
  constraint printers_name_unique unique (org_id, name)
);

comment on table public.printers is
  'A physical printer the office named, driven by one print station (0526, D-PS3).';

create index if not exists printers_station_idx on public.printers (station_id);

create table if not exists public.print_defaults (
  id          uuid        primary key default gen_random_uuid(),
  org_id      uuid        not null references public.organizations(id) on delete cascade,
  -- Null = the organization's default; a person = that person's own choice, which wins (D-PS4).
  user_id     uuid        references auth.users(id) on delete cascade,
  -- What is being printed. Labels today; a document printer later is a second purpose, not a table.
  purpose     text        not null default 'label' check (purpose in ('label')),
  printer_id  uuid        not null references public.printers(id) on delete restrict,
  updated_at  timestamptz not null default now(),
  updated_by  uuid        references auth.users(id) on delete set null
);

create unique index if not exists print_defaults_org_one
  on public.print_defaults (org_id, purpose) where user_id is null;
create unique index if not exists print_defaults_person_one
  on public.print_defaults (org_id, user_id, purpose) where user_id is not null;
create index if not exists print_defaults_printer_idx on public.print_defaults (printer_id);

comment on table public.print_defaults is
  'The printer a Print button uses without asking: one per organization and purpose, optionally overridden per person (0526, D-PS4).';

create table if not exists public.print_jobs (
  -- Client-generated, so a retried request is the same job (D-INV27).
  id            uuid        primary key default gen_random_uuid(),
  org_id        uuid        not null references public.organizations(id) on delete cascade,
  printer_id    uuid        not null references public.printers(id) on delete restrict,
  requested_by  uuid        references auth.users(id) on delete set null,
  -- What a person sees in the job list ("Label — Tablet A-0412").
  description   text        not null check (length(btrim(description)) between 1 and 200),
  label_count   integer     not null check (label_count between 1 and 500),
  -- The bytes in the printer's language, rendered when queued (D-PS2).
  payload       bytea       not null check (octet_length(payload) between 1 and 10485760),
  status        text        not null default 'queued'
                check (status in ('queued', 'sent', 'printed', 'failed', 'unknown', 'cancelled')),
  attempts      integer     not null default 0 check (attempts >= 0),
  error         text        check (length(error) <= 500),
  created_at    timestamptz not null default now(),
  sent_at       timestamptz,
  finished_at   timestamptz,
  -- One fact per status, never two columns that can disagree.
  constraint print_jobs_status_times check (
    case status
      when 'queued'    then sent_at is null and finished_at is null
      when 'sent'      then sent_at is not null and finished_at is null
      when 'unknown'   then sent_at is not null and finished_at is null
      when 'cancelled' then sent_at is null and finished_at is not null
      else finished_at is not null
    end
  )
);

comment on table public.print_jobs is
  'Every press of Print: queued → sent → printed | failed | unknown, or cancelled (0526). The queue and the record.';

create index if not exists print_jobs_queue_idx
  on public.print_jobs (printer_id, created_at) where status = 'queued';
create index if not exists print_jobs_sent_idx
  on public.print_jobs (printer_id, sent_at) where status = 'sent';
create index if not exists print_jobs_org_recent_idx
  on public.print_jobs (org_id, created_at desc);

-- ── SAME ORGANIZATION, SAID ONCE ────────────────────────────────────────────────────────────────
-- A printer on another org's station, a default naming another org's printer, a job for another
-- org's printer: one guard for all three. It also refuses a retired printer as a NEW default or a
-- NEW job's printer (PS004) — an existing default row is left alone when its printer retires, so the
-- screen can say "your default printer was retired" instead of the row silently vanishing.
create or replace function public.print_rows_same_org()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_org uuid;
  v_retired timestamptz;
begin
  if tg_table_name = 'printers' then
    select s.org_id into v_org from public.print_stations s where s.id = new.station_id;
  else
    select p.org_id, p.retired_at into v_org, v_retired from public.printers p where p.id = new.printer_id;
    if v_retired is not null and (tg_op = 'INSERT' or new.printer_id is distinct from old.printer_id) then
      raise exception 'printer % is retired and cannot be chosen', new.printer_id using errcode = 'PS004';
    end if;
  end if;
  if v_org is distinct from new.org_id then
    raise exception '%: the named % belongs to another organization', tg_table_name,
      case when tg_table_name = 'printers' then 'station' else 'printer' end
      using errcode = 'PS001';
  end if;
  return new;
end;
$$;

revoke all on function public.print_rows_same_org() from public, anon, authenticated;

drop trigger if exists trg_printers_same_org on public.printers;
create trigger trg_printers_same_org before insert or update of station_id, org_id on public.printers
  for each row execute function public.print_rows_same_org();
drop trigger if exists trg_print_defaults_same_org on public.print_defaults;
create trigger trg_print_defaults_same_org before insert or update of printer_id, org_id on public.print_defaults
  for each row execute function public.print_rows_same_org();
drop trigger if exists trg_print_jobs_same_org on public.print_jobs;
create trigger trg_print_jobs_same_org before insert or update of printer_id, org_id on public.print_jobs
  for each row execute function public.print_rows_same_org();

-- ── A JOB'S LIFE ONLY MOVES FORWARD ─────────────────────────────────────────────────────────────
-- Applies to the service role too: the API's own bugs are in scope (0161's reasoning). What it
-- printed, where and for whom is fixed once queued (PS003); the status moves only along the arrows
-- in the header (PS002); a job is never deleted except by its organization going (cascade) — a
-- retention prune of PAYLOADS is PS2's, and will clear the bytes, not the row.
create or replace function public.print_jobs_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'queued' or new.attempts <> 0 then
      raise exception 'a print job is created queued' using errcode = 'PS002';
    end if;
    return new;
  end if;
  if new.printer_id is distinct from old.printer_id
     or new.requested_by is distinct from old.requested_by
     or new.description is distinct from old.description
     or new.label_count is distinct from old.label_count
     or new.payload is distinct from old.payload
     or new.created_at is distinct from old.created_at then
    raise exception 'print job %: what, where and for whom are fixed once queued', old.id using errcode = 'PS003';
  end if;
  if new.status is distinct from old.status and not (
       (old.status = 'queued'  and new.status in ('sent', 'cancelled'))
    or (old.status = 'sent'    and new.status in ('printed', 'failed', 'unknown'))
    or (old.status = 'unknown' and new.status in ('printed', 'failed'))
  ) then
    raise exception 'print job %: % → % is not a step a job can take', old.id, old.status, new.status
      using errcode = 'PS002';
  end if;
  if new.status = old.status and old.status in ('printed', 'failed', 'cancelled')
     and (new.error is distinct from old.error or new.finished_at is distinct from old.finished_at
          or new.attempts is distinct from old.attempts or new.sent_at is distinct from old.sent_at) then
    raise exception 'print job % is finished', old.id using errcode = 'PS002';
  end if;
  return new;
end;
$$;

revoke all on function public.print_jobs_guard() from public, anon, authenticated;

drop trigger if exists trg_print_jobs_guard on public.print_jobs;
create trigger trg_print_jobs_guard before insert or update on public.print_jobs
  for each row execute function public.print_jobs_guard();

