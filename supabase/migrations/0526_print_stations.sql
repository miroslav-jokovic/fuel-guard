-- ── THE STATION'S TWO CALLS ─────────────────────────────────────────────────────────────────────
-- Service-role only: the API resolves the station from its token, then calls these with its id.
--
-- print_claim_next_job: the oldest queued job on any live printer this station drives, taken under
-- SKIP LOCKED so two station processes (a restart overlapping the old one) can never both take it.
-- Before claiming, any job this station took more than two minutes ago and never reported becomes
-- `unknown` — the header's reason. The call is also the station's heartbeat.
create or replace function public.print_claim_next_job(p_station uuid)
returns table (job_id uuid, system_name text, payload bytea, label_count integer)
language plpgsql
set search_path = ''
as $$
declare
  v_job public.print_jobs;
begin
  update public.print_stations s set last_seen_at = now()
   where s.id = p_station and s.revoked_at is null and s.token_hash is not null;
  if not found then
    return;
  end if;

  update public.print_jobs j
     set status = 'unknown', error = 'The print station stopped answering before it reported this job.'
   where j.status = 'sent'
     and j.sent_at < now() - interval '2 minutes'
     and j.printer_id in (select p.id from public.printers p where p.station_id = p_station);

  select j.* into v_job
    from public.print_jobs j
    join public.printers p on p.id = j.printer_id
   where p.station_id = p_station and p.retired_at is null and j.status = 'queued'
   order by j.created_at
   limit 1
   for update of j skip locked;

  if v_job.id is null then
    return;
  end if;

  update public.print_jobs j
     set status = 'sent', sent_at = now(), attempts = j.attempts + 1
   where j.id = v_job.id;

  return query
    select v_job.id, p.system_name, v_job.payload, v_job.label_count
      from public.printers p where p.id = v_job.printer_id;
end;
$$;

-- print_finish_job: the station's report. Refuses a job whose printer this station does not drive
-- (PS005) — a station's token must never settle another station's work. Reporting the same outcome
-- twice is answered with the current status, not an error: the station retries a report whose
-- response it lost, and that retry must not look like a failure.
create or replace function public.print_finish_job(p_station uuid, p_job uuid, p_ok boolean, p_error text)
returns text
language plpgsql
set search_path = ''
as $$
declare
  v_status text;
  v_station uuid;
begin
  select j.status, p.station_id into v_status, v_station
    from public.print_jobs j join public.printers p on p.id = j.printer_id
   where j.id = p_job
   for update of j;
  if v_station is distinct from p_station then
    raise exception 'print job % is not this station''s', p_job using errcode = 'PS005';
  end if;
  if v_status in ('printed', 'failed', 'cancelled') then
    return v_status;
  end if;
  update public.print_jobs j
     set status = case when p_ok then 'printed' else 'failed' end,
         finished_at = now(),
         error = case when p_ok then null else left(coalesce(nullif(btrim(p_error), ''), 'The printer refused the job.'), 500) end
   where j.id = p_job
  returning j.status into v_status;
  return v_status;
end;
$$;

revoke all on function public.print_claim_next_job(uuid) from public, anon, authenticated;
revoke all on function public.print_finish_job(uuid, uuid, boolean, text) from public, anon, authenticated;
