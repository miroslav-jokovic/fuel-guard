function render(entry, index) {
  const size = entry.landscape ? LANDSCAPE : PORTRAIT;
  const c = canvas(size.width, size.height, DESK);
  entry.build(c, 1000 + index * 37);
  return c;
}

function pixelDigest(rgb) {
  return createHash("sha256").update(rgb).digest("hex");
}

function build() {
  return CORPUS.map((entry, index) => {
    const c = render(entry, index);
    return {
      entry,
      canvas: c,
      record: {
        name: entry.name,
        file: `${entry.name}.png`,
        width: c.width,
        height: c.height,
        axes: entry.axes,
        pixelSha256: pixelDigest(c.rgb),
      },
    };
  });
}

const built = build();
const manifest = {
  // Bumped whenever the generator changes what it draws, so a stale checkout says so out loud rather
  // than reporting 24 mysterious digest mismatches.
  corpusVersion: "scanner-fixtures-1",
  note: "Generated by fixtures/generate.mjs. Digests are over raw RGB pixels, not file bytes — see that file's header.",
  fixtures: built.map((b) => b.record),
};

if (process.argv.includes("--check")) {
  const onDisk = JSON.parse(readFileSync(join(HERE, "manifest.json"), "utf8"));
  const drift = [];
  if (onDisk.corpusVersion !== manifest.corpusVersion) {
    drift.push(`corpusVersion: manifest says ${onDisk.corpusVersion}, generator says ${manifest.corpusVersion}`);
  }
  const byName = new Map(onDisk.fixtures.map((f) => [f.name, f]));
  for (const record of manifest.fixtures) {
    const previous = byName.get(record.name);
    if (!previous) drift.push(`${record.name}: absent from manifest.json`);
    else if (previous.pixelSha256 !== record.pixelSha256) drift.push(`${record.name}: pixels changed`);
    byName.delete(record.name);
  }
  for (const orphan of byName.keys()) drift.push(`${orphan}: in manifest.json but no longer generated`);

  if (drift.length > 0) {
    console.error("✗ fixture corpus drifted from manifest.json:\n" + drift.map((d) => `  ${d}`).join("\n"));
    console.error("\n  If the change was intended: bump corpusVersion, rerun `node fixtures/generate.mjs`,");
    console.error("  and say in the commit what moved and why — every metric baseline downstream shifts with it.");
    process.exit(1);
  }
  console.log(`✓ fixture corpus matches manifest.json (${manifest.fixtures.length} fixtures)`);
} else {
  for (const b of built) {
    writeFileSync(join(HERE, b.record.file), encodePng(b.canvas.rgb, b.canvas.width, b.canvas.height));
  }
  writeFileSync(join(HERE, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`✓ wrote ${manifest.fixtures.length} fixtures + manifest.json`);
}
