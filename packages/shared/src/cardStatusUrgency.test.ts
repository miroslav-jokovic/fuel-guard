describe("which card status changes are sent at once (Q-F3)", () => {
  const changes = REPLAY_2026_10_01_TO_06.map((line) => {
    const [iso, from, to] = line.split(" ") as [string, string, string];
    return { at: at(iso), from, to, timeZone: CHICAGO };
  });

  it("replays all 237 recorded changes, so the count below is not vacuous", () => {
    expect(changes).toHaveLength(237);
  });

  it("sends exactly the five that happened outside office hours", () => {
    const sent = changes.filter(cardStatusChangeIsUrgent).map((c) => c.at.toISOString());
    expect(sent).toEqual([
      "2026-10-01T23:25:33.000Z", // Thursday 18:25
      "2026-10-02T04:04:02.000Z", // Thursday 23:04
      "2026-10-04T08:05:37.000Z", // Sunday 03:05
      "2026-10-04T15:47:18.000Z", // Sunday 10:47
      "2026-10-05T02:52:21.000Z", // Sunday 21:52
    ]);
  });

  it("sends a FRAUD change at noon on a Tuesday, in either direction", () => {
    const noonTuesday = at("2026-10-06T17:00:00Z"); // 12:00 CDT
    expect(isOfficeHours(noonTuesday, CHICAGO)).toBe(true);
    expect(cardStatusChangeIsUrgent({ from: "ACTIVE", to: "FRAUD", at: noonTuesday, timeZone: CHICAGO })).toBe(true);
    expect(cardStatusChangeIsUrgent({ from: "Fraud", to: "ACTIVE", at: noonTuesday, timeZone: CHICAGO })).toBe(true);
    expect(cardStatusChangeIsUrgent({ from: "ACTIVE", to: "HOLD", at: noonTuesday, timeZone: CHICAGO })).toBe(false);
  });

  it("opens at 07:00 and closes at 18:00 on the org's clock", () => {
    expect(isOfficeHours(at("2026-10-06T11:59:00Z"), CHICAGO)).toBe(false); // 06:59
    expect(isOfficeHours(at("2026-10-06T12:00:00Z"), CHICAGO)).toBe(true); // 07:00
    expect(isOfficeHours(at("2026-10-06T22:59:00Z"), CHICAGO)).toBe(true); // 17:59
    expect(isOfficeHours(at("2026-10-06T23:00:00Z"), CHICAGO)).toBe(false); // 18:00
  });

  it("reads the weekday from the org's calendar, not from UTC", () => {
    // 08:30 Monday in Tokyo is 23:30 SUNDAY in UTC: open. 08:30 Saturday in Tokyo is 23:30 FRIDAY in
    // UTC: closed. A weekday read off the UTC instant gets both backwards.
    expect(isOfficeHours(at("2026-10-04T23:30:00Z"), "Asia/Tokyo")).toBe(true);
    expect(isOfficeHours(at("2026-10-02T23:30:00Z"), "Asia/Tokyo")).toBe(false);
    // 10:00 Saturday in Chicago is closed.
    expect(isOfficeHours(at("2026-10-03T15:00:00Z"), CHICAGO)).toBe(false);
  });

  it("finds FRAUD however EFS spells it", () => {
    expect(isFraudStatusChange("ACTIVE", "FRAUD")).toBe(true);
    expect(isFraudStatusChange("Fraud", "ACTIVE")).toBe(true);
    expect(isFraudStatusChange("HOLD", "ACTIVE")).toBe(false);
  });
});
