#!/usr/bin/env node
/**
 * Generates supabase/schema.generated.sql — the reviewable rendering of what the migrations
 * BUILD (D-SEP2 / program step P2.6, docs/plans/architecture/SEPARATION-PROGRAM-PLAN.md).
 *
 * Migrations stay the single source of truth (docs/MIGRATION-DISCIPLINE.md is unchanged); this
 * file exists because reconstructing a table's current shape means reading every migration that
 * touched it — fuel_transactions took 21 files before its 0261 split. The snapshot is applied-
 * state, dumped from the same in-process PGlite the test matrices use, sorted for stable diffs.
 * A migration PR now shows its net schema effect in one reviewable hunk, and the diff check
 * chained onto `lint:migrations` fails when someone edits the snapshot by hand or forgets to
 * regenerate — the `lint:codegen` convention.
 *
 * NOT a drift guard against production: that needs `supabase db diff --linked` and a DB secret
 * in CI (MIGRATION-DISCIPLINE §4, still optional). This guards the REPO's own coherence.
 */
import { PGlite } from "@electric-sql/pglite";
import { pg_trgm } from "@electric-sql/pglite/contrib/pg_trgm";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const MIG = join(ROOT, "supabase", "migrations");
const OUT = join(ROOT, "supabase", "schema.generated.sql");

const db = new PGlite({ extensions: { pg_trgm } });
await db.exec(`
  create schema if not exists auth;
  create table auth.users (id uuid primary key default gen_random_uuid(), email text);
  create schema if not exists storage;
  create table storage.buckets (
    id text primary key, name text, public boolean default false, file_size_limit bigint,
    allowed_mime_types text[], owner uuid,
    created_at timestamptz default now(), updated_at timestamptz default now()
  );
  create table storage.objects (
    id uuid primary key default gen_random_uuid(),
    bucket_id text, name text, owner uuid, created_at timestamptz default now()
  );
  alter table storage.objects enable row level security;
  create or replace function storage.foldername(name text)
  returns text[] language sql immutable as $fn$
    select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1];
  $fn$;
  create schema supabase_migrations;
  create table supabase_migrations.schema_migrations (version text primary key, name text, statements text[]);
  create role supabase_auth_admin nologin;
  create role authenticated nologin;
  create role anon nologin;
  create role service_role nologin bypassrls;
`);
await db.exec(
  "grant usage on schema public, storage to anon, authenticated, service_role;" +
    "alter default privileges in schema public grant all on tables to anon, authenticated, service_role;" +
    "alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;" +
    "alter default privileges in schema storage grant all on tables to anon, authenticated, service_role;",
);
const files = readdirSync(MIG).filter((f) => f.endsWith(".sql")).sort();
for (const f of files) {
  try { await db.exec(readFileSync(join(MIG, f), "utf8").replace(/create extension if not exists pgcrypto;?/gi, "")); }
  catch (e) { console.error(`migration ${f} failed: ${e.message}`); process.exit(1); }
}

const q = async (sql, params = []) => (await db.query(sql, params)).rows;
const lines = [];
lines.push("-- GENERATED by scripts/gen-schema-snapshot.mjs — do not edit.");
lines.push("-- The applied state of supabase/migrations/, dumped from PGlite and sorted for stable");
lines.push("-- diffs. Migrations remain the single source of truth; this is their rendering.");
lines.push(`-- Migrations applied: ${files.length} (through ${files[files.length - 1]})`);
lines.push("");

const tables = await q(`
  select c.relname as name, obj_description(c.oid) as comment, c.relrowsecurity as rls
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r'
   order by c.relname`);

for (const t of tables) {
  lines.push(`-- ============================================================================`);
  lines.push(`-- table ${t.name}${t.rls ? "  [RLS]" : "  [NO RLS]"}`);
  if (t.comment) for (const cl of String(t.comment).match(/.{1,96}(\s|$)/g) ?? []) lines.push(`--   ${cl.trim()}`);
  const cols = await q(`
    select column_name, data_type, is_nullable, column_default
      from information_schema.columns
     where table_schema = 'public' and table_name = $1
     order by ordinal_position`, [t.name]);
  for (const c of cols) {
    const parts = [`  ${c.column_name}`, c.data_type];
    if (c.is_nullable === "NO") parts.push("not null");
    if (c.column_default != null) parts.push(`default ${c.column_default}`);
    lines.push(parts.join("  "));
  }
  const cons = await q(`
    select conname, pg_get_constraintdef(oid) as def
      from pg_constraint
     where conrelid = ('public.' || quote_ident($1))::regclass
     order by conname`, [t.name]);
  for (const c of cons) lines.push(`  constraint ${c.conname}: ${c.def}`);
  const idx = await q(`
    select indexname, indexdef from pg_indexes
     where schemaname = 'public' and tablename = $1 order by indexname`, [t.name]);
  for (const i of idx) lines.push(`  index: ${i.indexdef.replace(/^CREATE /, "").toLowerCase()}`);
  const pol = await q(`
    select policyname, permissive, cmd, roles, qual, with_check
      from pg_policies where schemaname = 'public' and tablename = $1 order by policyname`, [t.name]);
  for (const p of pol)
    lines.push(`  policy ${p.policyname} [${p.permissive}/${p.cmd}] roles=${JSON.stringify(p.roles)} using=${p.qual ?? "-"} check=${p.with_check ?? "-"}`);
  const trg = await q(`
    select tgname, pg_get_triggerdef(t.oid) as def
      from pg_trigger t
     where t.tgrelid = ('public.' || quote_ident($1))::regclass and not t.tgisinternal
     order by tgname`, [t.name]);
  for (const tr of trg) lines.push(`  trigger: ${tr.def.toLowerCase()}`);
  lines.push("");
}

lines.push(`-- ============================================================================`);
lines.push(`-- functions (public schema)`);
const fns = await q(`
  select p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public'
   order by 1`);
for (const f of fns) lines.push(`  ${f.sig}`);
lines.push("");

writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`✓ wrote supabase/schema.generated.sql — ${tables.length} tables, ${fns.length} functions, ${lines.length} lines.`);
