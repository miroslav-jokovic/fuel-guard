#!/usr/bin/env node
/**
 * Generates `packages/shared/src/fleetpal/fieldManifest.generated.json` — resource → field-name
 * list — from the FleetPal OpenAPI document.
 *
 * ⚠ **THIS SCRIPT CANNOT RUN IN CI, AND THAT IS THE WHOLE REASON THE MANIFEST EXISTS.**
 * `docs/FleetPal/` is gitignored (the vendor's document, and 830 KB of generated JSON nobody could
 * review in a diff — see the `.gitignore` block and `docs/FleetPal/SOURCE.md`). So the spec is in
 * every developer's working tree and in no CI checkout. A gate that read the spec directly would
 * therefore SKIP on every CI run while looking like it passed, which is worse than no gate:
 * `lint:wsdl` spent ten days crashing on a stale path with nobody able to notice, and root
 * `CLAUDE.md` records that as the argument.
 *
 * The split that fixes it: this script runs by hand, beside a working tree that holds the spec, and
 * commits a small derived artefact. `check-fleetpal-contract.mjs` then compares that artefact
 * against `packages/shared/src/fleetpalContract.ts` — two files that ARE both in CI — so the gate
 * runs everywhere and fails on a real disagreement.
 *
 * **Field NAMES only, deliberately.** No descriptions, no examples, no VMRS code text. Two reasons,
 * and they are independent: the descriptions are the vendor's prose and are not ours to
 * redistribute (the same reason the spec is ignored), and the VMRS ones are licensed TMC material
 * that D-FP8 keeps out of our storage entirely. A manifest of names is a statement about the shape
 * of an interface we integrate with, which is ours to record.
 *
 * Usage:  node scripts/gen-fleetpal-manifest.mjs [--check]
 *   --check  regenerate in memory and exit non-zero if the committed file differs, without writing.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SPEC = join(ROOT, "docs", "FleetPal", "Fleetpal API.json");
const OUT = join(ROOT, "packages", "shared", "src", "fleetpal", "fieldManifest.generated.json");

/**
 * The schemas we ingest, in the order FLEETPAL-INTEGRATION-PLAN.md §F1 lists them. Deliberately NOT
 * "every schema in the document": customers, sales orders and customer invoices are out of scope
 * (§7 — Silvicom does not sell shop work to third parties), and listing them here would put a gate
 * behind contracts nobody intends to write.
 */
const RESOURCES = [
  "Unit",
  "WorkOrder",
  "Job",
  "JobItem",
  "ServiceHistory",
  "Meter",
  "PMSchedule",
  "Interval",
  "Part",
  "Vendor",
  "Shop",
  "Defect",
  "Issue",
  "Expiration",
  "PurchaseOrder",
  "POInvoice",
  "POReceipt",
  "POReceiptItem",
];

/**
 * The enums we pin. A vendor adding a member to one of these is an additive change they are allowed
 * to make inside v1, and it must not take the feed down — so the contract reads them as strings and
 * the manifest records the members we KNOW, which is what lets a test notice a new one appearing
 * rather than a parser reject it. See `fleetpalContract.ts` for that distinction, which is the one
 * thing in this integration most likely to be got wrong.
 */
const ENUMS = [
  "OwnershipEnum",
  "LineItemTypeEnum",
  "MeterTypeEnum",
  "RepairPriorityClassEnum",
  "WorkOrderPriorityEnum",
  "IssueStatusEnum",
  "IssuePriorityEnum",
  "POReceiptItemTypeEnum",
  "OrderStatusEnum",
  "OrderTypeEnum",
  "POItemTypeEnum",
  "POInvoiceTypeEnum",
  "VendorTypeEnum",
  "IntervalTypeEnum",
  "TimeIntervalEnum",
  "UnitOfMeasureEnum",
];

function build(spec) {
  const schemas = spec.components?.schemas ?? {};
  const resources = {};
  for (const name of RESOURCES) {
    const schema = schemas[name];
    if (!schema) throw new Error(`schema ${name} is not in the spec — has the document moved?`);
    resources[name] = Object.keys(schema.properties ?? {}).sort();
  }
  const enums = {};
  for (const name of ENUMS) {
    const schema = schemas[name];
    if (!schema?.enum) throw new Error(`enum ${name} is not in the spec — has the document moved?`);
    // NOT sorted: an enum's order is the vendor's and carries no meaning, but keeping it stable
    // makes the diff of an ADDED member one line rather than a reshuffle.
    enums[name] = [...schema.enum];
  }
  const paths = {};
  for (const [path, ops] of Object.entries(spec.paths ?? {})) {
    if (path.includes("{id}") || !ops.get) continue;
    paths[path] = (ops.get.parameters ?? []).map((p) => p.name).sort();
  }
  return {
    "//": "GENERATED by scripts/gen-fleetpal-manifest.mjs from the gitignored FleetPal OpenAPI document. Field NAMES only — no vendor prose, no VMRS text. Checked by scripts/check-fleetpal-contract.mjs, which is what runs in CI. Regenerate by hand when docs/FleetPal/ changes; see docs/FleetPal/SOURCE.md for the version this was built from.",
    specVersion: "v1",
    resources,
    enums,
    listFilters: paths,
  };
}

const check = process.argv.includes("--check");

if (!existsSync(SPEC)) {
  // Not an error. The spec is absent in CI by design, and the gate that matters
  // (check-fleetpal-contract.mjs) reads the committed manifest instead.
  console.log(
    "· fleetpal manifest: docs/FleetPal/ is absent (expected in CI) — nothing to regenerate.",
  );
  process.exit(0);
}

const built = JSON.stringify(build(JSON.parse(readFileSync(SPEC, "utf8"))), null, 2) + "\n";

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== built) {
    console.error(
      "✗ fleetpal manifest is stale — the spec in your working tree disagrees with the committed\n" +
        "  manifest. Run `node scripts/gen-fleetpal-manifest.mjs` and commit the result.",
    );
    process.exit(1);
  }
  console.log("✓ fleetpal manifest matches the spec in this working tree.");
  process.exit(0);
}

writeFileSync(OUT, built);
console.log(
  `✓ wrote ${OUT.replace(ROOT, "")} — ${RESOURCES.length} resources, ${ENUMS.length} enums.`,
);
